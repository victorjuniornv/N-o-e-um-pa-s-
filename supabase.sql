create table if not exists public.houses (
  id bigint generated by default as identity primary key,
  city text not null,
  owner text not null,
  name text not null,
  x double precision not null default 0.5,
  y double precision not null default 0.5,
  color text not null default '#ffd166',
  roof text not null default '#b94c3c',
  created_at timestamptz not null default now()
);

alter table public.houses enable row level security;

-- Protótipo: permite ler e criar casas sem login.
-- Para um jogo público de verdade, adicione autenticação e regras anti-spam.
create policy "public can read houses"
on public.houses for select
to anon, authenticated
using (true);

create policy "public can create houses"
on public.houses for insert
to anon, authenticated
with check (length(owner) between 1 and 20 and length(name) between 1 and 30);
